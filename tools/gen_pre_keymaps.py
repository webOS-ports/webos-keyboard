#!/usr/bin/env python3
"""Generate the Pre Keyboard's letter rows for every language plugin.

The Pre Keyboard draws the Palm Pre's grid. The languages the Pre itself
shipped with (English, French, German, Spanish, Italian), and any language
whose phone layout is plain QWERTY or QWERTZ, use that grid with the Pre's
printed number and symbol alternates (src/pre/prekeymap.cpp). Every other
language gets its letters from its own phone layout here, so the Pre Keyboard
types what the stock keyboard types:

    python3 tools/gen_pre_keymaps.py > src/pre/prelanguages_generated.cpp

Reads plugins/<dir>/qml/Keyboard_<lang>_phone.qml (the pinyin plugin's is zh): the first three KeyRows'
CharKeys (label, shifted, extended, extendedShifted). Run it again after
changing a phone layout, and commit the result.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent

# Each language in its own name, as the globe's menu and the space bar show it.
NAMES = {
    "ar": "العربية", "cs": "Čeština", "da": "Dansk", "de": "Deutsch",
    "en": "English", "es": "Español", "fi": "Suomi", "fr": "Français",
    "he": "עברית", "hu": "Magyar", "it": "Italiano", "nl": "Nederlands",
    "no": "Norsk", "zh": "中文 (拼音)", "pl": "Polski", "pt": "Português",
    "ru": "Русский", "sv": "Svenska", "uk": "Українська",
}

RTL = {"ar", "he"}

# The Pre's own grids, as the Pre printed them; see prelanguage.cpp.
PRE_SHIPPED = {"en": "Qwerty", "fr": "Azerty", "de": "Qwertz", "es": "Qwerty", "it": "Qwerty"}
PRE_ROWS = {
    "Qwerty": ["qwertyuiop", "asdfghjkl", "zxcvbnm"],
    "Qwertz": ["qwertzuiop", "asdfghjkl", "yxcvbnm"],
}

# Hold-list entries that are not characters to type.
NOT_TEXT = {"Rec", "Mute"}


def strings(s, key):
    m = re.search(key + r':\s*\[([^\]]*)\]', s)
    if not m:
        return []
    return [x for x in re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(1)) if x not in NOT_TEXT]


def one(s, key):
    m = re.search(r'(?<![A-Za-z])' + key + r':\s*"((?:[^"\\]|\\.)*)"', s)
    return m.group(1) if m else None


def letter_rows(path):
    rows, cur = [], None
    for line in path.read_text(encoding="utf-8").splitlines():
        s = line.strip()
        if s.startswith("KeyRow"):
            cur = []
            continue
        if cur is not None and s.startswith("CharKey"):
            label = one(s, "label")
            if label is None:
                sys.exit(f"{path}: a CharKey without a label: {s}")
            cur.append({
                "text": label,
                "shifted": one(s, "shifted") or "",
                "extended": strings(s, "extended"),
                "extendedShifted": strings(s, "extendedShifted"),
            })
        if cur is not None and s == "}" and cur:
            rows.append(cur)
            cur = None
            if len(rows) == 3:
                break
    if len(rows) != 3:
        sys.exit(f"{path}: expected three letter rows, found {len(rows)}")
    return rows


def cpp(s):
    out = []
    for ch in s:
        if ch in '\\"':
            out.append("\\" + ch)
        elif ord(ch) < 0x20:
            out.append("\\x%02x" % ord(ch))
        else:
            out.append(ch)
    return 'u"' + "".join(out) + '"'


def cpp_list(items):
    return "{ " + ", ".join("QStringLiteral(" + cpp(x) + ")" for x in items) + " }" if items else "{}"


def main():
    files = {}
    for f in (ROOT / "plugins").glob("*/qml/Keyboard_*_phone.qml"):
        files[f.name[len("Keyboard_"):-len("_phone.qml")]] = f
    langs = sorted(files)
    missing = [l for l in langs if l not in NAMES]
    if missing:
        sys.exit("No name for: " + ", ".join(missing))

    print("// Generated by tools/gen_pre_keymaps.py from plugins/*/qml/Keyboard_*_phone.qml.")
    print("// Do not edit: change the phone layout and run the script again.")
    print()
    print('#include "prelanguage.h"')
    print()
    print("namespace Pre {")
    print()
    print("const QList<Language> &Language::all()")
    print("{")
    print("    static const QList<Language> languages = {")
    for lang in langs:
        rows = letter_rows(files[lang])
        plain = ["".join(k["text"] for k in r) for r in rows]
        grid = PRE_SHIPPED.get(lang)
        if grid is None:
            for name, pre in PRE_ROWS.items():
                if plain == pre:
                    grid = name
        rtl = "true" if lang in RTL else "false"
        if grid:
            print(f"        preGrid(QStringLiteral({cpp(lang)}), QStringLiteral({cpp(NAMES[lang])}), Layout::{grid}),")
            continue
        print(f"        ownRows(QStringLiteral({cpp(lang)}), QStringLiteral({cpp(NAMES[lang])}), {rtl}, {{")
        for r in rows:
            print("            {")
            for k in r:
                print(f"                {{ QStringLiteral({cpp(k['text'])}), QStringLiteral({cpp(k['shifted'])}),")
                print(f"                  {cpp_list(k['extended'])},")
                print(f"                  {cpp_list(k['extendedShifted'])} }},")
            print("            },")
        print("        }),")
    print("    };")
    print("    return languages;")
    print("}")
    print()
    print("} // namespace Pre")


if __name__ == "__main__":
    main()
